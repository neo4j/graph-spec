package golang

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strings"

	"github.com/neo4j/graph-spec/tools/schema-generator/internal/model"
)

type Options struct {
	Package    string
	SchemaName string
}

func Generate(m *model.Model, opts Options) ([]byte, error) {
	if err := checkNames(m); err != nil {
		return nil, err
	}

	g := &generator{imports: map[string]bool{}}
	// write types first as they determine the required imports
	for _, t := range m.NamedTypes {
		g.printf("\n")
		g.writeType(t)
	}

	var out bytes.Buffer
	writeHeaderAndImports(&out, opts, g.imports)
	out.Write(g.buf.Bytes())

	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated invalid Go source: %w\n%s", err, out.Bytes())
	}
	return src, nil
}

func writeHeaderAndImports(out *bytes.Buffer, opts Options, imports map[string]bool) {
	fmt.Fprintf(out, "// Code generated by schema-generator from %s. DO NOT EDIT.", opts.SchemaName)
	fmt.Fprintf(out, "\n\npackage %s\n", opts.Package)
	if len(imports) == 0 {
		return
	}
	out.WriteString("\nimport (\n")
	for _, imp := range slices.Sorted(maps.Keys(imports)) {
		fmt.Fprintf(out, "\t%q\n", imp)
	}
	out.WriteString(")\n")
}

type generator struct {
	buf     bytes.Buffer
	imports map[string]bool
}

func (g *generator) use(pkgs ...string) {
	for _, p := range pkgs {
		g.imports[p] = true
	}
}

func (g *generator) printf(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
}

func (g *generator) doc(text, indent string) {
	text = strings.TrimSpace(text)
	if text == "" {
		return
	}
	// format.Source trims trailing whitespace from comments, so blank lines need no special case.
	for _, line := range strings.Split(text, "\n") {
		g.printf("%s// %s\n", indent, line)
	}
}

func (g *generator) writeType(t *model.NamedType) {
	g.doc(t.Doc, "")
	switch t.Kind {
	case model.Struct:
		g.writeStruct(t)
	case model.Enum:
		g.writeEnum(t)
	case model.Union:
		g.writeUnion(t)
	}
}

func (g *generator) writeStruct(named *model.NamedType) {
	if len(named.Fields) == 0 {
		g.printf("type %s struct{}\n", typeName(named))
	} else {
		g.printf("type %s struct {\n", typeName(named))
		for _, f := range named.Fields {
			g.doc(f.Doc, "\t")
			tag := f.JSONName
			if !f.Required {
				tag += ",omitempty"
			}
			g.printf("\t%s %s `json:%q`\n", identifier(f.JSONName), fieldType(f), tag)
		}
		g.printf("}\n")
	}
	if len(named.Tags) == 0 {
		return
	}

	for _, t := range named.Tags {
		g.printf("\nfunc (%s) %s() {}\n", typeName(named), markerName(t.Union))
		g.printf("\nfunc (%s) %s() string { return %q }\n", typeName(named), discriminatorMethod(t.Union), t.Value)
	}

	// A variant in several unions sharing a discriminator property writes it once.
	var tags []*model.Tag
	for _, t := range named.Tags {
		if !slices.ContainsFunc(tags, func(o *model.Tag) bool { return o.Property == t.Property }) {
			tags = append(tags, t)
		}
	}
	g.use("encoding/json")
	g.printf("\nfunc (v %s) MarshalJSON() ([]byte, error) {\n", typeName(named))
	g.printf("\ttype plain %s\n", typeName(named))
	g.printf("\treturn json.Marshal(struct {\n")
	for _, t := range tags {
		g.printf("\t\t%s string `json:%q`\n", identifier(t.Property), t.Property)
	}
	g.printf("\t\tplain\n\t}{")
	for _, t := range tags {
		g.printf("%q, ", t.Value)
	}
	g.printf("plain(v)})\n}\n")
}

func (g *generator) writeEnum(named *model.NamedType) {
	name, values := typeName(named), valuesVarName(named)
	g.printf("type %s string\n\nconst (\n", name)
	for _, v := range named.Values {
		g.printf("\t%s %s = %q\n", valueName(named, v), name, v)
	}
	g.printf(")\n\n// %s lists every %s value.\nvar %s = []%s{\n", values, name, values, name)
	for _, v := range named.Values {
		g.printf("\t%s,\n", valueName(named, v))
	}
	g.printf("}\n")
}

func (g *generator) writeUnion(named *model.NamedType) {
	g.use("bytes", "encoding/json", "fmt")
	name, iface, disc := typeName(named), interfaceName(named), named.Discriminator

	g.printf("type %s struct {\n\t%s\n}\n", name, iface)

	var variants []string
	for _, v := range named.Variants {
		variants = append(variants, typeName(v.Named))
	}
	g.printf("\n// %s is implemented by the variants of %s: %s.\n", iface, name, strings.Join(variants, ", "))
	g.printf("type %s interface {\n\t%s() string\n\t%s()\n}\n", iface, discriminatorMethod(named), markerName(named))

	g.printf(`
func (u %[1]s) MarshalJSON() ([]byte, error) {
	if u.%[2]s == nil {
		return []byte("null"), nil
	}
	return json.Marshal(u.%[2]s)
}

func (u *%[1]s) UnmarshalJSON(data []byte) error {
	if bytes.Equal(bytes.TrimSpace(data), []byte("null")) {
		u.%[2]s = nil
		return nil
	}
	var probe struct {
		Value *string `+"`json:%[3]q`"+`
	}
	if err := json.Unmarshal(data, &probe); err != nil {
		return fmt.Errorf("decoding %[1]s: %%w", err)
	}
	if probe.Value == nil {
		return fmt.Errorf("decoding %[1]s: missing %%q property", %[3]q)
	}
	switch *probe.Value {
`, name, iface, disc)
	for _, v := range named.Variants {
		g.printf(`	case %q:
		var v %s
		if err := json.Unmarshal(data, &v); err != nil {
			return fmt.Errorf("decoding %s: %%w", err)
		}
		u.%s = v
`, v.Value, typeName(v.Named), name, iface)
	}
	g.printf(`	default:
		return fmt.Errorf("decoding %s: unknown %%q value %%q", %q, *probe.Value)
	}
	return nil
}
`, name, disc)
}

func goType(t *model.Type) string {
	var s string
	switch t.Kind {
	case model.String:
		s = "string"
	case model.Integer:
		s = "int64"
	case model.Number:
		s = "float64"
	case model.Boolean:
		s = "bool"
	case model.Any:
		s = "any"
	case model.Array:
		s = "[]" + goType(t.Elem)
	case model.Map:
		s = "map[string]" + goType(t.Elem)
	default:
		s = typeName(t.Named)
	}
	if t.Nullable && t.Kind != model.Any {
		return "*" + s
	}
	return s
}

func fieldType(f *model.Field) string {
	if !f.Required && !f.Type.Nullable && f.Type.Kind != model.Any {
		return "*" + goType(f.Type)
	}
	return goType(f.Type)
}
